// Bundles the installer and @geld/core/nightly into one dependency-free file, what npx runs and what CI attaches to each release.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8'));
await build({
  entryPoints: ['src/bin.ts'],
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  outfile: 'dist/geld-nightly.mjs',
  legalComments: 'none',
  banner: { js: '#!/usr/bin/env node\n// Generated by pnpm --filter geld-nightly build, do not edit.' },
  define: { INSTALLER_VERSION: JSON.stringify(version) },
});
